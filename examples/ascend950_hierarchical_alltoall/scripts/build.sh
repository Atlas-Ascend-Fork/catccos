set -eo pipefail
CURRENT_DIR=$(pwd)
SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" &>/dev/null && pwd)
PROJECT_ROOT=$( dirname $( dirname $(dirname "$SCRIPT_DIR")))

GROUP_SIZE=${GROUP_SIZE:-16}
if ! [[ "${GROUP_SIZE}" =~ ^([1-9]|[12][0-9]|3[0-2])$ ]]; then
    echo "[ERROR] GROUP_SIZE must be an integer in [1, 32]" >&2
    exit 1
fi

RDMA_BACKEND=${SHMEM_RDMA_BACKEND:-HNS_1825}
HNS_PI_ON_CHIP=${SHMEM_HNS_1825_PI_ON_CHIP:-}
case "${RDMA_BACKEND}" in
    HNS_1825)
        if [[ "${HNS_PI_ON_CHIP}" != 0 && "${HNS_PI_ON_CHIP}" != 1 ]]; then
            echo "[ERROR] Set SHMEM_HNS_1825_PI_ON_CHIP=0 or 1 to match the SHMEM SDK and target firmware." >&2
            exit 1
        fi
        ;;
    XSCALE)
        if [ -n "${HNS_PI_ON_CHIP}" ]; then
            echo "[ERROR] SHMEM_HNS_1825_PI_ON_CHIP is only valid for HNS_1825." >&2
            exit 1
        fi
        ;;
    *)
        echo "[ERROR] SHMEM_RDMA_BACKEND must be HNS_1825 or XSCALE." >&2
        exit 1
        ;;
esac

# Read optional flags before setup.sh reuses SHMEM_BUILD_ARGS as an array.
read -ra hierarchical_shmem_args <<< "${SHMEM_BUILD_ARGS:--enable_rdma -rdma_backend ${RDMA_BACKEND} -multi_link}"
source "$PROJECT_ROOT/examples/utils/setup.sh" -soc_type Ascend950 "${hierarchical_shmem_args[@]}" || {
    echo "[ERROR] Running setup.sh in $PROJECT_ROOT/examples/utils failed."
    exit 1
}

SOURCE_DIR=$PROJECT_ROOT
BUILD_DIR=$PROJECT_ROOT/build
mkdir -p $BUILD_DIR
cmake -B $BUILD_DIR -S $SOURCE_DIR -DCATCCOS_BUILD_TESTS=OFF -DCATLASS_BISHENG_ARCH=a5 \
    -DCATCCOS_HIERARCHICAL_GROUP_SIZE="${GROUP_SIZE}" \
    -DCATCCOS_RDMA_BACKEND="${RDMA_BACKEND}" \
    -DCATCCOS_HNS_1825_PI_ON_CHIP="${HNS_PI_ON_CHIP}"

# The device kernel is generated by an add_custom_command whose DEPENDS only lists the
# example's main.cpp. Header-only changes under include/catccos therefore do not rebuild
# lib<target>_impl.so, and a stale kernel can silently run with a newer host ABI. Remove
# the kernel library so every build.sh invocation reflects the current headers.
rm -f "${BUILD_DIR}/bin/libascend950_hierarchical_alltoall_impl.so"

cmake --build $BUILD_DIR --target ascend950_hierarchical_alltoall -j "${BUILD_JOBS:-2}"

cp "${SHMEM_HOME_PATH}/version.info" "${BUILD_DIR}/bin/hierarchical_shmem_version.info"

cd $CURRENT_DIR
